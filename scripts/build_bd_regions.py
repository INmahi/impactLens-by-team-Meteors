"""Build the Bangladesh region outlines (country, 8 divisions, 64 districts) from ONE source, so borders coincide.

    uv run python scripts/build_bd_regions.py      # rewrites pipeline/synthetic/bangladesh.py

Inputs (data/raw/geoboundaries/, see docs/datasets/bangladesh-boundaries.md):
- geoBoundaries-BGD-ADM2_simplified.geojson: 64 districts, Bangladesh Bureau of Statistics (BBS) / OCHA ROAP via
  geoBoundaries gbOpen, 2020, CC BY 3.0 IGO. This is the geometry for all three levels.
- geoBoundaries-BGD-ADM1_simplified.geojson: 8 divisions (2015, CC0), used ONLY to assign each district to its
  division (by an interior point) and for the division ISO codes.
Steps: coverage-simplify the 64 districts together (shared edges stay shared, 0.012 degree ~ 1.2 km), divisions =
union of their districts, country = union of all districts. Official spellings (2018 renames) are applied.
"""

from __future__ import annotations

import io
import json
import re
from pathlib import Path

import shapely
from shapely.geometry import MultiPolygon, Polygon, shape
from shapely.geometry.polygon import orient

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "data" / "raw" / "geoboundaries"
OUT = ROOT / "pipeline" / "synthetic" / "bangladesh.py"
TOL = 0.012
MIN_PART = 0.004  # square degrees (~45 km2): drop tiny islands/slivers

SPELLING = {
    "Barisal": "Barishal", "Bogra": "Bogura", "Brahamanbaria": "Brahmanbaria", "Chittagong": "Chattogram",
    "Comilla": "Cumilla", "Jessore": "Jashore", "Nawabganj": "Chapai Nawabganj", "Netrakona": "Netrokona",
    "Maulvibazar": "Moulvibazar",
}
DIVISION = {  # ISO code -> (id, official name)
    "BD-A": ("bd_barishal", "Barishal"), "BD-B": ("bd_chattogram", "Chattogram"), "BD-C": ("bd_dhaka", "Dhaka"),
    "BD-D": ("bd_khulna", "Khulna"), "BD-E": ("bd_rajshahi", "Rajshahi"), "BD-F": ("bd_rangpur", "Rangpur"),
    "BD-G": ("bd_sylhet", "Sylhet"), "BD-H": ("bd_mymensingh", "Mymensingh"),
}


def slug(name: str) -> str:
    return re.sub(r"[^a-z]+", "_", name.lower()).strip("_")


def rings(geom) -> list[list[tuple[float, float]]]:
    parts = list(geom.geoms) if isinstance(geom, MultiPolygon) else [geom]
    out = []
    for p in sorted(parts, key=lambda p: -p.area):
        if p.area < MIN_PART:
            continue
        p = orient(Polygon(p.exterior), 1.0)  # outer ring only, counter-clockwise
        pts = [(round(x, 3), round(y, 3)) for x, y in p.exterior.coords]
        if pts[0] != pts[-1]:
            pts.append(pts[0])
        out.append(pts)
    return out


def bbox(geom) -> tuple[float, float, float, float]:
    w, s, e, n = geom.bounds
    return (round(w - 0.05, 2), round(s - 0.05, 2), round(e + 0.05, 2), round(n + 0.05, 2))


def fmt_rings(rs, indent: str) -> list[str]:
    lines = []
    for r in rs:
        lines.append(f"{indent}[")
        row = [f"({x}, {y})" for x, y in r]
        for i in range(0, len(row), 6):
            lines.append(f"{indent}    " + ", ".join(row[i:i + 6]) + ",")
        lines.append(f"{indent}],")
    return lines


def main() -> int:
    adm2 = json.loads((RAW / "geoBoundaries-BGD-ADM2_simplified.geojson").read_text(encoding="utf-8"))["features"]
    adm1 = json.loads((RAW / "geoBoundaries-BGD-ADM1_simplified.geojson").read_text(encoding="utf-8"))["features"]
    assert len(adm2) == 64 and len(adm1) == 8, (len(adm2), len(adm1))
    div_geoms = {f["properties"]["shapeISO"]: shape(f["geometry"]).buffer(0) for f in adm1}
    names = [SPELLING.get(f["properties"]["shapeName"], f["properties"]["shapeName"]) for f in adm2]
    geoms = [shape(f["geometry"]).buffer(0) for f in adm2]
    simple = list(shapely.coverage_simplify(geoms, TOL))
    districts = []
    for name, g0, g in zip(names, geoms, simple):
        pt = g0.representative_point()
        iso = max(div_geoms, key=lambda k: div_geoms[k].intersection(g0.buffer(0)).area if div_geoms[k].contains(pt) or True else 0)
        if not div_geoms[iso].contains(pt):
            iso = max(div_geoms, key=lambda k: div_geoms[k].intersection(g0).area)
        districts.append((name, DIVISION[iso][0], g))
    country = shapely.union_all([g for _, _, g in districts])
    divisions = {}
    for iso, (did, dname) in DIVISION.items():
        members = [g for _, d, g in districts if d == did]
        divisions[did] = (dname, iso, shapely.union_all(members), len(members))
    counts = {did: v[3] for did, v in divisions.items()}
    print("districts per division:", counts)
    assert sum(counts.values()) == 64

    head = '''"""Bangladesh outlines: the country, its 8 divisions and 64 districts (M12, 2026-11-13). GENERATED by
scripts/build_bd_regions.py: do not edit by hand.

Source geometry for all three levels: geoBoundaries gbOpen BGD ADM2 (Bangladesh Bureau of Statistics / OCHA ROAP,
2020, CC BY 3.0 IGO), coverage-simplified together (0.012 degree, ~1.2 km) so neighbouring borders coincide.
Divisions = union of their districts; country = union of all 64. District-to-division assignment uses geoBoundaries
ADM1 (2015, CC0). Official spellings applied (Barishal, Bogura, Brahmanbaria, Chattogram, Cumilla, Jashore,
Chapai Nawabganj, Netrokona, Moulvibazar). Parts smaller than 0.004 square degrees dropped; rings counter-clockwise.
"""

from __future__ import annotations

Ring = list[tuple[float, float]]
'''
    lines = [head, "# One ring per part (MultiPolygon), lon/lat degrees, closed.", "BANGLADESH: list[Ring] = ["]
    lines += fmt_rings(rings(country), "    ")
    lines.append("]")
    lines.append("")
    lines.append("# id -> (name, ISO 3166-2 code, bbox [w, s, e, n], rings)")
    lines.append("BD_DIVISIONS: dict[str, tuple[str, str, tuple[float, float, float, float], list[Ring]]] = {")
    for did, (dname, iso, g, _n) in sorted(divisions.items(), key=lambda kv: kv[1][0]):
        lines.append(f'    "{did}": ("{dname}", "{iso}", {bbox(g)}, [')
        lines += fmt_rings(rings(g), "        ")
        lines.append("    ]),")
    lines.append("}")
    lines.append("")
    lines.append("# id -> (name, division id, bbox [w, s, e, n], rings)")
    lines.append("BD_DISTRICTS: dict[str, tuple[str, str, tuple[float, float, float, float], list[Ring]]] = {")
    for name, did, g in sorted(districts, key=lambda t: t[0]):
        lines.append(f'    "bd_{slug(name)}_district": ("{name}", "{did}", {bbox(g)}, [')
        lines += fmt_rings(rings(g), "        ")
        lines.append("    ]),")
    lines.append("}")
    io.open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    npts = sum(len(r) for _, _, g in districts for r in rings(g))
    print(f"wrote {OUT.relative_to(ROOT)}: country {sum(len(r) for r in rings(country))} pts, districts {npts} pts")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
